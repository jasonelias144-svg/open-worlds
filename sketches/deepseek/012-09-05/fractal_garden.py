@dataclass(frozen=True)
class SlotRect:
    slot_id: str
    x: int
    y: int
    w: int
    h: int

    def to_dict(self):
        return {"slot_id": self.slot_id, "x": self.x, "y": self.y,
                "w": self.w, "h": self.h}

    @classmethod
    def from_dict(cls, d):
        return cls(slot_id=d["slot_id"], x=d["x"], y=d["y"],
                   w=d["w"], h=d["h"])

    def root_cells(self) -> List[Tuple[int, int]]:
        return [(x, self.y + self.h - 1)
                for x in range(self.x, self.x + self.w)]


@dataclass(frozen=True)
class PlantAssignment:
    slot_id: str
    initial_tip: Tuple[int, int, int]
    plant_params: Dict[str, int]

    def to_dict(self):
        return {
            "slot_id": self.slot_id,
            "initial_tip": list(self.initial_tip),
            "plant_params": dict(self.plant_params),
        }

    @classmethod
    def from_dict(cls, d):
        return cls(
            slot_id=d["slot_id"],
            initial_tip=tuple(d["initial_tip"]),
            plant_params=dict(d["plant_params"]))


