@dataclass(frozen=True)
class GardenTemplate:
    template_id: str
    slot_rects: List[SlotRect]
    water_width: int
    water_height: int
    rain_rate: int = 64
    evap_rate: int = 24
    water_max: int = 8
    energy_cap: int = 40
    growth_cost: int = 1
    light_level: int = 10
    branch_policy: Optional[Dict] = None
    # branch_policy: None = sandbox
    # {
    #   "control": {"light_level": (3, 10)},
    #   "terminal": {"rain_rate": (16, 128),
    #                "evap_rate": (8, 64),
    #                "light_level": (1, 10)},
    # }

    def to_dict(self):
        return {
            "template_id": self.template_id,
            "slot_rects": [s.to_dict() for s in self.slot_rects],
            "water_width": self.water_width,
            "water_height": self.water_height,
            "rain_rate": self.rain_rate,
            "evap_rate": self.evap_rate,
            "water_max": self.water_max,
            "energy_cap": self.energy_cap,
            "growth_cost": self.growth_cost,
            "light_level": self.light_level,
            "branch_policy": self.branch_policy,
        }

    def template_hash(self):
        return _hash(self.to_dict())

    @property
    def num_slots(self):
        return len(self.slot_rects)


