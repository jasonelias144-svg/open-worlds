def _line_cells(x1, y1, x2, y2):
    cells = []
    dx = abs(x2 - x1); dy = -abs(y2 - y1)
    sx = 1 if x1 < x2 else -1
    sy = 1 if y1 < y2 else -1
    err = dx + dy
    x, y = x1, y1
    while True:
        cells.append((x, y))
        if x == x2 and y == y2:
            return cells
        e2 = 2 * err
        if e2 >= dy:
            err += dy; x += sx
        if e2 <= dx:
            err += dx; y += sy


def render_garden(garden: FractalGarden) -> str:
    plant_cells = {}
    for slot_id, plant in garden.plants().items():
        for seg in plant.segments():
            for (x, y) in _line_cells(*seg):
                plant_cells[(x, y)] = "#"
        for (x, y, _d, _dep) in plant.frontier():
            plant_cells[(x, y)] = "*"
    lines = []
    for y in range(garden.grid.height - 1):
        row = []
        for x in range(garden.grid.width):
            if (x, y) in plant_cells:
                row.append(plant_cells[(x, y)])
            else:
                v = garden.grid.get(x, y)
                row.append("." if v == 0 else
                           ("W" if v >= garden.template.water_max
                            else str(v)))
        lines.append("".join(row))
    lines.append("=" * garden.grid.width)
    return "\n".join(lines)


def render_energy(garden: FractalGarden) -> str:
    return ", ".join(
        f"{sid}={garden.energy(sid)}/{garden.template.energy_cap}"
        for sid in sorted(garden.energy()))


