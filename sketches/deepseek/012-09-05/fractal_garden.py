"""
fractal_garden.py — The garden as a composite world.

Proposal sketch, not a course step. Builds on fractal_world_v3
(the plant) and water_particles (the water rules).

Design summary:

  - A garden is a composite world. It owns the shared water, the
    slots (sub-rectangles of the bed), the plant roster, and the
    per-plant energy pool.
  - Each plant is an AtomicFractalWorld from fractal_world_v3,
    nested inside the garden. The garden does not re-implement
    the plant's law — it calls plant.grow() and plant.can_grow()
    when it has energy to give.
  - Water is the interaction medium. Per garden tick: rain, fall,
    soak (into each plant's energy), flow, evaporate. Then grow
    each plant that has enough energy.
  - The plant's own water param still gates its growth. A plant
    with own_water = 0 refuses to grow even when the garden offers
    energy. Composition rule: the parent supplies, the child
    decides.
  - The garden can branch. Same protocol as v3's BranchRequest:
    a new garden inherits the parent's water grid and plants'
    geometry at the branch point, gets new params, continues.

Simplifications (marked for the standard's review):

  - `sig` fields are flat, not W3C DataIntegrityProof objects.
  - Key names in body() should be checked against the schema.
  - Plant subworlds use their own keys, generated by the garden.
    In production, a plant's key would be derived from the garden's
    (hierarchical), or issued by the garden's keeper.
  - light_level is a global scalar. Spatial light (shade from
    taller plants) is a future refinement.
  - No plant death from lack of water (stalling only). Dieback is
    a future stage.
  - Garden-level water/light params do not propagate to the
    plants' own params. A plant's params are fixed at seed time.
    To change a plant's params, the garden would have to branch
    the plant — not implemented here.
  - No cross-garden messaging. The superworld (botanical garden)
    is the next stage.
"""

