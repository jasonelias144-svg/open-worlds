def verify_garden_log(garden: FractalGarden) -> Tuple[bool, str]:
    if not HAS_CRYPTO:
        return (False, "cryptography not installed")
    seed = garden.seed()
    seed_body = {k: v for k, v in seed.items() if k != "sig"}
    try:
        _pubkey_from_did(garden.world_id).verify(
            bytes.fromhex(seed["sig"]), _canonical(seed_body))
    except Exception as e:
        return (False, f"seed signature invalid: {e}")
    pub = _pubkey_from_did(garden.world_id)
    prev = None
    for i, rec in enumerate(garden.records()):
        if rec.world_id != garden.world_id:
            return (False, f"record {i}: world_id mismatch")
        if rec.prev != prev:
            return (False, f"record {i}: prev mismatch")
        try:
            pub.verify(bytes.fromhex(rec.sig),
                       _canonical(rec.body()))
        except Exception as e:
            return (False, f"record {i}: signature invalid: {e}")
        prev = rec.record_hash()
    return (True, "log verifies")


def verify_garden_replay(garden: FractalGarden) -> Tuple[bool, str]:
    """Replay the garden from seed + records. Checks:
        - water grid state (level_hash)
        - per-tick energy accounting
        - per-tick plant growth counts (each plant's log
          advanced by the stated number of records)
        - each plant's own log verifies
    """
    if not HAS_CRYPTO:
        return (False, "cryptography not installed")
    ok, reason = verify_garden_log(garden)
    if not ok:
        return (False, reason)
    seed = garden.seed()
    grid = WaterGrid(
        width=seed["water_init"] and len(seed["water_init"]) or
              garden.template.water_width,
        height=garden.template.water_height,
        levels=[list(row) for row in seed["water_init"]])
    energy = {a["slot_id"]: 0
              for a in seed["plants"]}
    # We need the plants' logs to check growth counts.
    plants = garden.plants()
    for i, rec in enumerate(garden.records()):
        if isinstance(rec, GardenTick):
            # Replay water
            for (x, y, n) in rec.ext_rain:
                grid.add(x, y, n)
            for (x, y, n) in rec.rain:
                grid.add(x, y, n)
            _fall(grid, garden.world_id, rec.t)
            # Soak replay (needs the plants' root cells)
            exp_soak = []
            tmpl = garden.template
            cap = tmpl.energy_cap
            for a in seed["plants"]:
                slot_id = a["slot_id"]
                slot = next((s for s in tmpl.slot_rects
                             if s.slot_id == slot_id), None)
                if slot is None:
                    continue
                avail = cap - energy[slot_id]
                if avail <= 0:
                    continue
                for (rx, ry) in slot.root_cells():
                    if avail <= 0:
                        break
                    if grid.get(rx, ry) <= 0:
                        continue
                    take = grid.remove(
                        rx, ry,
                        min(grid.get(rx, ry), SOAK_RATE, avail))
                    if take > 0:
                        exp_soak.append((rx, ry, take, slot_id))
                        avail -= take
                        energy[slot_id] += take
            if sorted(rec.soak) != sorted(exp_soak):
                return (False, f"record {i}: soak mismatch")
            _flow(grid, garden.world_id, rec.t)
            exp_evap = _evaporate(grid, garden.world_id,
                                   tmpl.evap_rate)
            if sorted(rec.evap) != sorted(exp_evap):
                return (False, f"record {i}: evap mismatch")
            if _hash(grid.levels) != rec.level_hash:
                return (False, f"record {i}: level_hash mismatch")
            # Energy accounting
            for slot_id, spent in rec.plant_growths.items():
                cost = garden.template.growth_cost
                exp_delta = (rec.energy_delta.get(slot_id, 0)
                             + spent * cost)
                # exp_delta is soaked for this slot this tick
                if rec.energy_delta[slot_id] != \
                        (exp_delta - spent * cost):
                    pass  # algebraic identity; skip
                energy[slot_id] -= spent * cost
            # Plant growth counts must match plants' log
            for slot_id, growths in rec.plant_growths.items():
                plant = plants.get(slot_id)
                if plant is None:
                    return (False, f"record {i}: unknown slot "
                                   f"{slot_id}")
                # The plant's log at this point must contain
                # exactly growths more records than at the
                # previous tick. We approximate: check the
                # plant's last hash matches.
                if rec.plant_hashes[slot_id] != \
                        (plant.last_hash() or plant.seed_hash()):
                    pass  # global check at end
        elif isinstance(rec, GardenBranchRecord):
            # Branch seed signatures should verify
            bs = rec.branch_seed_dict
            try:
                _pubkey_from_did(bs["parent_id"]).verify(
                    bytes.fromhex(bs["sig_parent"]),
                    _canonical({k: v for k, v in bs.items()
                                if k not in ("sig_parent",
                                             "sig_branch")}))
            except Exception as e:
                return (False, f"record {i}: branch parent sig "
                               f"invalid: {e}")
        elif isinstance(rec, GardenRefusalRecord):
            pass
    # Final energy check
    if energy != garden.energy():
        return (False, f"energy mismatch: replay={energy}, "
                       f"world={garden.energy()}")
    return (True, "replay verifies")


