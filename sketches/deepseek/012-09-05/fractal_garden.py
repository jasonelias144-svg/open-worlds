def demo(artifact_dir=None):
    """Two plants in a garden. One grows (own_water=10), one
    refuses (own_water=0) — despite both receiving garden energy.
    The garden also refuses a branch request from an observer,
    accepts one from a controller. The accepted branch creates a
    dimmer, wetter garden that grows its plants under new params.

    Verifies: parent log, branch log, and replay of both."""
    import json as _json
    from pathlib import Path

    if not HAS_CRYPTO:
        raise RuntimeError("demo requires `cryptography`")

    if artifact_dir is None:
        artifact_dir = "artifacts"
